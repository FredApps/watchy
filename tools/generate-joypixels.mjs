// Regenerates src/joypixelsShortcodes.ts from emojibase-data.
//
// Discord's shortcodes are the JoyPixels (ex-EmojiOne) set, while Watchy's own
// emoji data uses the CLDR names. Emitting JoyPixels as a separate map lets
// both spellings resolve - ":open_mouth:" and ":face_with_open_mouth:" alike.
//
//   node tools/generate-joypixels.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const joypixels = JSON.parse(
  readFileSync(join(root, "node_modules/emojibase-data/en/shortcodes/joypixels.json"), "utf8"),
);

// Watchy's existing CLDR map decides the canonical spelling of each emoji, so
// both maps hand the renderer identical strings (variation selectors included).
const emojiData = readFileSync(join(root, "src/emojiData.ts"), "utf8");
const cldr = JSON.parse(emojiData.match(/export const chatEmojiShortcodes[^=]*= (\{.*?\});/s)[1]);
const canonical = new Map();
for (const emoji of Object.values(cldr)) {
  canonical.set(emoji.replace(/️/g, ""), emoji);
}
// Only emoji Watchy actually carries; the rest of JoyPixels is skin-tone and
// flag variants that appear in neither the picker nor the CLDR map.
const supported = new Set(
  Object.keys(JSON.parse(emojiData.match(/export const chatEmojiSearchText[^=]*= (\{.*?\});/s)[1])),
);

const fromHexcode = (hexcode) =>
  String.fromCodePoint(...hexcode.split("-").map((point) => Number.parseInt(point, 16)));

const shortcodes = {};
for (const [hexcode, value] of Object.entries(joypixels)) {
  const raw = fromHexcode(hexcode);
  const emoji = canonical.get(raw.replace(/️/g, "")) ?? raw;
  if (!supported.has(emoji)) {
    continue;
  }
  for (const code of Array.isArray(value) ? value : [value]) {
    const key = code.toLowerCase();
    if (key in shortcodes) {
      continue;
    }
    // Keys the CLDR map already spells the same way are dead weight. The ~20
    // that disagree are kept so Discord's reading wins: :dog: is the face,
    // :sunglasses: is the smiley.
    if (!(key in cldr) || cldr[key].replace(/️/g, "") !== emoji.replace(/️/g, "")) {
      shortcodes[key] = emoji;
    }
  }
}

const sorted = Object.fromEntries(Object.entries(shortcodes).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  join(root, "src/joypixelsShortcodes.ts"),
  `// Generated by tools/generate-joypixels.mjs - do not edit by hand.\n` +
    `// JoyPixels/EmojiOne shortcodes, the set Discord uses.\n` +
    `export const joypixelsShortcodes: Record<string, string> = ${JSON.stringify(sorted)};\n`,
);

console.log(`wrote ${Object.keys(sorted).length} JoyPixels shortcodes`);
